# Q.3) Write a program in Python for data type conversion from:
# - int to string
# - int to float
# - string to int
# - string to float
# - float to int
# - float to string

# int to string
i = 10
s = str(i)
print("int to string:", s, type(s))

# int to float
i = 10
f = float(i)
print("int to float:", f, type(f))

# string to int
s = "25"
i = int(s)
print("string to int:", i, type(i))

# string to float
s = "25.5"
f = float(s)
print("string to float:", f, type(f))

# float to int
f = 25.8
i = int(f)
print("float to int:", i, type(i))

# float to string
f = 25.8
s = str(f)
print("float to string:", s, type(s))